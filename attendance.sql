-- 온라인 서점 출석체크 기능 설정
-- database.sql을 실행한 뒤 Supabase SQL Editor에서 실행합니다.

BEGIN;

-- 로그인한 사용자의 일별 출석 기록을 저장합니다.
CREATE TABLE IF NOT EXISTS public.attendances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  attendance_date date NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT attendances_user_id_attendance_date_key UNIQUE (user_id, attendance_date)
);

-- 본인의 출석 내역 조회를 빠르게 처리합니다.
CREATE INDEX IF NOT EXISTS attendances_user_id_attendance_date_idx
  ON public.attendances (user_id, attendance_date DESC);

ALTER TABLE public.attendances ENABLE ROW LEVEL SECURITY;

-- 웹 사용자의 기본 테이블 권한을 회수한 뒤 조회 권한만 부여합니다.
REVOKE ALL ON TABLE public.attendances FROM anon, authenticated;
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON TABLE public.attendances TO authenticated;

-- 로그인한 사용자는 자신의 출석 내역만 조회할 수 있습니다.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'attendances'
      AND policyname = '본인 출석 내역만 조회 가능'
  ) THEN
    CREATE POLICY "본인 출석 내역만 조회 가능"
      ON public.attendances
      FOR SELECT
      TO authenticated
      USING (auth.uid() = user_id);
  END IF;
END;
$$;

-- 출석은 이 함수로만 처리합니다. 날짜는 한국 시간 기준으로 결정합니다.
CREATE OR REPLACE FUNCTION public.check_in()
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id uuid;
  v_attendance_id bigint;
BEGIN
  v_user_id := auth.uid();

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION '로그인한 사용자만 출석할 수 있습니다.';
  END IF;

  INSERT INTO public.attendances (user_id, attendance_date)
  VALUES (v_user_id, (timezone('Asia/Seoul', now()))::date)
  ON CONFLICT (user_id, attendance_date) DO NOTHING
  RETURNING id INTO v_attendance_id;

  IF v_attendance_id IS NULL THEN
    RAISE EXCEPTION '오늘은 이미 출석했습니다.';
  END IF;

  RETURN v_attendance_id;
END;
$$;

-- 함수 실행은 로그인한 사용자에게만 허용합니다.
REVOKE ALL ON FUNCTION public.check_in() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.check_in() TO authenticated;

COMMIT;
